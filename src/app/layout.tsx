import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import "./globals.css";
import { Providers } from "./providers";
import { THEME_INIT_SCRIPT } from "@/lib/theme";

// Fonts live in the repository (src/app/fonts, all SIL Open Font License) and
// are served from our own domain: no request to Google at runtime and none at
// build time either, so a Google outage can never break a deploy. Latin
// subset only — covers German text, umlauts, ß and €. Hanken Grotesk is a
// variable font (one file for every weight).
const bevan = localFont({
  src: [{ path: "./fonts/Bevan-400.woff2", weight: "400", style: "normal" }],
  variable: "--font-bevan",
  display: "swap",
});
const saira = localFont({
  src: [
    { path: "./fonts/SairaCondensed-400.woff2", weight: "400", style: "normal" },
    { path: "./fonts/SairaCondensed-500.woff2", weight: "500", style: "normal" },
    { path: "./fonts/SairaCondensed-600.woff2", weight: "600", style: "normal" },
    { path: "./fonts/SairaCondensed-700.woff2", weight: "700", style: "normal" },
    { path: "./fonts/SairaCondensed-800.woff2", weight: "800", style: "normal" },
    { path: "./fonts/SairaCondensed-900.woff2", weight: "900", style: "normal" },
  ],
  variable: "--font-saira",
  display: "swap",
});
const hanken = localFont({
  src: [
    { path: "./fonts/HankenGrotesk-Variable.woff2", weight: "400 800", style: "normal" },
    { path: "./fonts/HankenGrotesk-Italic-Variable.woff2", weight: "400 800", style: "italic" },
  ],
  variable: "--font-hanken",
  display: "swap",
});

// iOS launch images (generated by scripts/generate-splash.mjs), one per
// device size — iOS picks the one whose media query matches.
const SPLASH: [number, number, number][] = [
  [440, 956, 3],
  [402, 874, 3],
  [430, 932, 3],
  [393, 852, 3],
  [390, 844, 3],
  [375, 812, 3],
  [414, 896, 3],
  [414, 896, 2],
  [414, 736, 3],
  [375, 667, 2],
];

export const metadata: Metadata = {
  title: "ClubTermine",
  description: "Trainings, Events und Spieltage deines Padel-Clubs",
  manifest: "/manifest.webmanifest",
  appleWebApp: {
    capable: true,
    title: "ClubTermine",
    // Content runs under the status bar; headers already pad for the safe area.
    statusBarStyle: "black-translucent",
    startupImage: SPLASH.map(([w, h, dpr]) => ({
      url: `/splash/${w}x${h}@${dpr}x.png`,
      media: `(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)`,
    })),
  },
  // Private club app: keep it out of search results.
  robots: { index: false, follow: false },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  themeColor: "#14223F",
  // Required for env(safe-area-inset-*) to resolve to non-zero values in
  // WebKit — without it every safe-area CSS value below stays 0.
  viewportFit: "cover",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="de" className={`${bevan.variable} ${saira.variable} ${hanken.variable}`} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
      </head>
      <body>
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
